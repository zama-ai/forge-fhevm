#!/usr/bin/env python3
"""Generate the OZ-free host-contract surface consumed by FhevmTest.

Emits, from the compiled artifacts of the vendored host contracts:

  src/generated/HostBytecode.sol     creation/runtime bytecode blobs
  src/generated/interfaces/I*.sol    ABI-derived interfaces (errors + events included)

Why: the vendored host contracts under src/fhevm-host/ import OpenZeppelin.
Because Foundry remappings are project-global, any consumer inheriting
FhevmTest inherits our OZ pin too. Shipping bytecode + interfaces instead of
source keeps the consumer's compile graph free of OZ, so downstream repos pick
their own version.

Run via `make generate` — never edit the output by hand.
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "out"
GEN = ROOT / "src" / "generated"

BANNER = """// SPDX-License-Identifier: BSD-3-Clause-Clear
// AUTOGENERATED by `make generate` from the vendored host contracts.
// DO NOT EDIT — your changes will be overwritten. See script/gen/generate.py.
pragma solidity ^0.8.27;
"""

# Deployed with CREATE so constructors run: every UUPS contract bakes
# `UUPSUpgradeable.__self = address(this)` into its runtime code, and `_checkProxy`
# reverts unless that immutable matches the ERC1967 slot.
CREATION = [
    ("ACL", "ACL.sol"),
    ("HCULimit", "HCULimit.sol"),
    ("FHEVMExecutor", "FHEVMExecutor.sol"),
    ("InputVerifier", "InputVerifier.sol"),
    ("KMSVerifier", "KMSVerifier.sol"),
    ("EmptyUUPSProxy", "EmptyUUPSProxy.sol"),
    ("EmptyUUPSProxyACL", "EmptyUUPSProxyACL.sol"),
    ("HCULimitNoDepthCap", "HCULimitNoDepthCap.sol"),
]

# These land at fixed canonical addresses and carry no immutables, so etching
# the runtime blob is byte-for-byte equivalent to constructing them.
RUNTIME = [
    ("PauserSet", "PauserSet.sol"),
    ("DeployableERC1967Proxy", "DeployableERC1967Proxy.sol"),
]

INTERFACES = [
    ("IACL", "ACL", "ACL.sol"),
    ("IFHEVMExecutor", "FHEVMExecutor", "FHEVMExecutor.sol"),
    ("IHCULimit", "HCULimit", "HCULimit.sol"),
    ("IInputVerifier", "InputVerifier", "InputVerifier.sol"),
    ("IKMSVerifier", "KMSVerifier", "KMSVerifier.sol"),
    ("IEmptyUUPSProxy", "EmptyUUPSProxy", "EmptyUUPSProxy.sol"),
    ("IEmptyUUPSProxyACL", "EmptyUUPSProxyACL", "EmptyUUPSProxyACL.sol"),
]

ALL_BLOBS = [(n, f, "creation") for n, f in CREATION] + [(n, f, "runtime") for n, f in RUNTIME]


def screaming(name: str) -> str:
    """ACL -> ACL, FHEVMExecutor -> FHEVM_EXECUTOR, EmptyUUPSProxyACL -> EMPTY_UUPS_PROXY_ACL."""
    parts, buf = [], ""
    for i, ch in enumerate(name):
        nxt = name[i + 1] if i + 1 < len(name) else ""
        if buf and ch.isupper() and (buf[-1].islower() or (nxt.islower() and nxt != "")):
            parts.append(buf)
            buf = ch
        else:
            buf += ch
    parts.append(buf)
    return "_".join(p.upper() for p in parts if p)


def artifact(name: str, sol: str) -> dict:
    path = OUT / sol / f"{name}.json"
    if not path.exists():
        sys.exit(f"missing artifact {path} — run `forge build` first")
    return json.loads(path.read_text())


def gen_bytecode() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    chunks, report = [BANNER], []
    for name, sol, kind in ALL_BLOBS:
        art = artifact(name, sol)
        key = "bytecode" if kind == "creation" else "deployedBytecode"
        code = art[key]["object"]
        if code.startswith("0x"):
            code = code[2:]
        if not code:
            sys.exit(f"{name}: empty {kind} bytecode")
        if "__$" in code:
            sys.exit(f"{name}: unlinked library placeholder in bytecode")
        const = f"{screaming(name)}_{kind.upper()}_CODE"
        chunks.append(f'\n/// @dev {name} {kind} bytecode ({len(code) // 2} bytes).\nbytes constant {const} = hex"{code}";\n')
        report.append((name, kind, len(code) // 2))
    (GEN / "HostBytecode.sol").write_text("".join(chunks))
    total = sum(r[2] for r in report)
    for name, kind, size in report:
        print(f"  {name:<24} {kind:<8} {size:>7,} bytes")
    print(f"  {'TOTAL':<24} {'':<8} {total:>7,} bytes")


def gen_interfaces() -> None:
    d = GEN / "interfaces"
    d.mkdir(parents=True, exist_ok=True)
    for iface, name, sol in INTERFACES:
        art = OUT / sol / f"{name}.json"
        res = subprocess.run(
            ["cast", "interface", str(art), "--name", iface],
            capture_output=True, text=True, cwd=ROOT,
        )
        if res.returncode != 0:
            sys.exit(f"cast interface failed for {name}:\n{res.stderr}")
        lines, imports = [], []
        for line in res.stdout.splitlines():
            if line.startswith("// SPDX-License-Identifier") or line.startswith("pragma solidity"):
                continue  # cast emits its own SPDX + a loose pragma; replace with ours
            # `cast interface` flattens enum parameters into a local `type X is uint8`, a
            # *distinct* type from the shared enum callers pass — re-point at the real one.
            if line.strip() == "type FheType is uint8;":
                imports.append('import {FheType} from "../../fhevm-host/contracts/shared/FheType.sol";')
                continue
            lines.append(line)
        head = ("\n".join(imports) + "\n") if imports else ""
        body = "\n".join(lines).strip()
        (d / f"{iface}.sol").write_text(f"{BANNER}\n{head}\n{body}\n")
        print(f"  {iface}" + (" (+FheType)" if imports else ""))


def main() -> None:
    print("generating bytecode blobs:")
    gen_bytecode()
    print("generating interfaces:")
    gen_interfaces()
    subprocess.run(["forge", "fmt", str(GEN)], cwd=ROOT, check=False)
    print("done")


if __name__ == "__main__":
    main()
